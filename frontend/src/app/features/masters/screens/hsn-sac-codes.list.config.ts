// masters.api.ts's HsnSacCodeRow stops at code/code_type/description, but the
// endpoint's real response model carries four more fields: build_lookup_router
// generates its out_schema straight from masters_simple.py's field dict, which
// for HSN/SAC is code, code_type, description, linked_tax_head_id, is_custom,
// custom_gst_type, custom_gst_rate_pct (+ id, is_active). Linked Tax is what
// §3.11 is actually about, so it is declared here rather than left off the
// screen; widening the interface itself belongs in masters.api.ts, which
// another owner holds this pass — see the batch report.
interface HsnSacRow extends HsnSacCodeRow {
  linked_tax_head_id: string | null;
  is_custom: boolean;
  custom_gst_type: string | null;
  custom_gst_rate_pct: number | null;
}

// §3.11: the link is "to a real, editable tax head — never a fixed label", so
// the label comes from the Taxes endpoint itself. TaxHead's identifying field
// is tax_name, not the `name` RefDataService defaults to.
//
// Deliberately the UNFILTERED list, unlike the Linked Tax picker on the form
// (hsn-sac-codes.form.config.ts, which narrows to the in-force Sales/Purchase
// heads the API will actually accept). This one only has to RESOLVE ids that
// are already stored: a code linked to a head that has since been retired or
// deactivated must keep showing that head's name rather than "Unknown", and
// the filter below has to be able to name it for the same reason. Hence
// include_inactive — read, not write.
const TAX_HEAD_REF = { endpoint: '/masters/taxes/options?include_inactive=true', labelKey: 'label' };

// The stored values are the two-letter codes the column is typed for
// (hsn_sac_codes.code_type is String(3)); the labels are the prototype's own
// option strings (app-forms.js 'm.hsn' — 'SAC – Services', 'HSN – Goods').
const CODE_TYPE_OPTIONS = [
  { value: 'SAC', label: 'SAC – Services' },
  { value: 'HSN', label: 'HSN – Goods' },
];

// Same two members TaxHead.tax_type uses for its GST heads (taxes.form.config
// .ts, tax_engine.py) — §3.11: the custom fallback "matches the same two types
// every configured GST head already uses".
const GST_TYPE_OPTIONS = [
  { value: 'GST_IGST', label: 'GST — IGST' },
  { value: 'GST_CGST_SGST', label: 'GST — CGST + SGST' },
];

/** §3.11's "— Custom —" escape hatch, rendered as one readable cell: it is the
 * reason a row can legitimately have no Linked Tax Head, so showing the two
 * fields together explains the em-dash in the column beside it. Null (not '')
 * for a non-custom row so ListScreenComponent renders its own em-dash. */
function customRate(row: HsnSacRow): string | null {
  if (!row.is_custom) return null;
  const type = GST_TYPE_OPTIONS.find((o) => o.value === row.custom_gst_type)?.label ?? row.custom_gst_type ?? 'Custom';
  const raw = row.custom_gst_rate_pct;
  // Guard the null BEFORE Number(): Number(null) is 0, which would print a
  // rate of "0%" for a row that simply has none recorded. Numeric(7,4) itself
  // arrives as 18 / 18.0 / "18.0000" depending on the encoder, and Number()
  // normalises all three to the figure a person would write.
  if (raw === null || raw === undefined) return type;
  const pct = Number(raw);
  return Number.isFinite(pct) ? `${type} @ ${pct}%` : type;
}

