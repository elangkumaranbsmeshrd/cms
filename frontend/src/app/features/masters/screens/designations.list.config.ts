import { ListScreenConfig } from '../../../shared/screens/screen.types';
import { DesignationRow } from '../masters.api';

const DEPARTMENT_REF = { endpoint: '/masters/departments/options', labelKey: 'label' };

const config: ListScreenConfig<DesignationRow> = {
  shape: 'list',
  id: 'masters.designations',
  title: 'Designation / Job Title',
  specRef: '§3.10',
  recordNoun: 'designation',
  // The prototype's own words for this screen (data.js masters.designation.add
  // desc) — the list entry itself carries no desc string.
  description: 'The controlled list of job titles staff can hold.',
  endpoint: '/masters/designations',
  exportable: true,
  rowId: (row) => row.id,
  rowRoute: (row) => ['/masters/designations', row.id, 'edit'],
  createRoute: ['/masters/designations', 'new'],
  createLabel: 'Add Designation',
  // Generated by masters_lookup.build_lookup_router: list_rows takes only
  // search, include_inactive and format, so those two are the only filters
  // that can round-trip (and the only ones the export is exact for).
  searchParam: 'search',
  // §3a — masters_simple.py now passes search_field=["name", "code"].
  searchFields: ['name', 'code'],
  // The prototype's "Status: Active / Inactive / All Statuses" filter maps onto
  // this: include_inactive=false (default) is Active-only, true is All.
  // Rendered as the "Show inactive" checkbox, chipped as "Status: Including
  // inactive". No Inactive-only option — the endpoint has no `status=` param.
  includeInactiveParam: 'include_inactive',
  filters: [
    {
      // Client transport: list_rows has no department_id param
      // (masters_lookup.py:164-171). Options come from the Department lookup
      // itself so the values are ids and the labels are names — the same
      // endpoint the column below resolves through, so filter and column can't
      // disagree. Stands in for the prototype's "Used — Any" slot, which has no
      // backing field on Designation at all.
      key: 'department_id',
      label: 'Linked Department',
      kind: 'select',
      transport: 'client',
      allLabel: 'All Departments',
      optionsRef: DEPARTMENT_REF,
      predicate: (row, v) => String(row.department_id ?? '') === String(v),
    },
    {
      // Level / Grade is free text (§3.10: "e.g. Junior, Senior, Lead"), so
      // there is no options endpoint to draw from — the distinct values present
      // in the loaded rows are the honest option list. Client transport for the
      // same reason as above: no level_grade query param exists.
      key: 'level_grade',
      label: 'Level / Grade',
      kind: 'select',
      transport: 'client',
      allLabel: 'All Levels / Grades',
      optionsFromRows: (rows) => {
        const seen = new Set<string>();
        for (const row of rows) {
          const value = String(row.level_grade ?? '').trim();
          if (value) seen.add(value);
        }
        return [...seen].sort((a, b) => a.localeCompare(b)).map((value) => ({ value, label: value }));
      },
      predicate: (row, v) => String(row.level_grade ?? '') === String(v),
    },
    {
      key: 'is_referenced',
      label: 'Used',
      kind: 'tristate',
      transport: 'server',
      param: 'is_referenced',
      allLabel: 'Used — Any',
    },
  ],
  columns: [
    { key: 'name', header: 'Designation', cellClass: 'cell-strong' },
    { key: 'code', header: 'Code', type: 'code' },
    // §3.10's Fields Table calls this "Linked Department"; the raw response
    // sends a bare departments.id, resolved to a name by RefDataService.
    { key: 'department_id', header: 'Linked Department', ref: DEPARTMENT_REF },
    { key: 'level_grade', header: 'Level / Grade' },
    { key: 'is_active', header: 'Status', type: 'status', compute: (row) => (row.is_active ? 'Active' : 'Inactive') },
    { key: 'is_referenced', header: 'Used', type: 'status' },
  ],
  rowActions: [
    {
      // §4.3 audit: without this, a deactivated designation could never come
      // back through the built UI — masters_lookup.py's factory only ever
      // had the one-way POST /{id}/deactivate. Added the mirror POST
      // /{id}/activate to the factory itself, so this is real (not an inert
      // 404 stub). §3.10's own Fields Table calls Status "Toggle
      // (Active/Inactive)" — this restores the other half of it.
      label: 'Activate',
      endpoint: (row) => `/masters/designations/${row.id}/activate`,
      screenAction: 'delete',
      visible: (row) => !row.is_active,
    },
    {
      // Masters §3.0 rule 1: "Delete and Deactivate are Super Admin only… only
      // Super Admin sees it." PolicyStore.can(id, 'delete') is the same action
      // require_screen(..., action="delete") guards both endpoints with.
      label: 'Deactivate',
      endpoint: (row) => `/masters/designations/${row.id}/deactivate`,
      screenAction: 'delete',
      visible: (row) => row.is_active,
      confirm: '§3.10: a designation assigned to any Employee record is never hard-deleted. Deactivating removes it from every dropdown while the staff records already holding it keep naming it. Continue?',
    },
    {
      label: 'Delete',
      method: 'DELETE',
      endpoint: (row) => `/masters/designations/${row.id}`,
      screenAction: 'delete',
      visible: (row) => !row.is_referenced,
      confirm: 'Delete this designation permanently? This only succeeds while nothing references it.',
    },
  ],
  defaultPageSize: 50,
  emptyText: 'No designations configured.',
};

export default config;
